/**
 * Gemini APIで会話を生成（複数キャラ対応）
 */
export async function generateChat(apiKey, playerChar, personality, recentTasks, friends = []) {
    if (!apiKey) {
        const mock = getPersonalizedMockChat(personality);
        return {
            messages: [
                { speaker: 'player', text: mock.player },
                { speaker: 'npc', text: mock.npc },
            ],
        };
    }

    const playerTone = getToneStyle(personality);
    const topicsText = extractTopics(recentTasks);
    const timeHint = getTimeHint();

    // 会話参加者を決定
    let opponent;
    if (friends.length > 0) {
        const pick = friends[Math.floor(Math.random() * friends.length)];
        opponent = {
            name: pick.name,
            tone: getToneStyle(pick.personality),
            desc: pick.personalitySummary || 'ふしぎなやつ',
        };
    } else {
        opponent = {
            name: NPC_CHARACTER.name,
            tone: 'のんびり屋で天然。「〜だよ〜」が口癖',
            desc: NPC_CHARACTER.personalitySummary,
        };
    }

    const prompt = `あなたは2体のモンスターのゆるい日常会話を書くライターです。
それぞれの性格に合った、テンプレ感のない自然な会話を1往復書いてください。

【${playerChar.name}】(Lv${playerChar.level})
- 口調: ${playerTone}
- 最近やったこと: ${topicsText}

【${opponent.name}】
- 口調: ${opponent.tone}
- 性格: ${opponent.desc}

シチュエーション: ${timeHint}

必須ルール:
- 各セリフ30文字以内
- ひらがな多め
- ${playerChar.name}は最近やったことの話題を絡める
- 毎回違う話題と言い回し。テンプレっぽさを排除
- 直前の会話と同じ内容にしない
- 絵文字・顔文字は禁止
- JSON出力のみ: {"player":"セリフ","npc":"セリフ"}`;

    try {
        const response = await fetch(`${GEMINI_API_URL}?key=${apiKey}`, {
            method: 'POST',
            headers: { 'Content-Type': 'application/json' },
            body: JSON.stringify({
                contents: [{ parts: [{ text: prompt }] }],
                generationConfig: {
                    temperature: 1.1,
                    maxOutputTokens: 200,
                },
            }),
        });

        if (!response.ok) {
            console.warn('Gemini API応答エラー:', response.status);
            const mock = getPersonalizedMockChat(personality);
            return {
                messages: [
                    { speaker: 'player', text: mock.player },
                    { speaker: 'npc', text: mock.npc, speakerName: opponent.name },
                ],
            };
        }

        const data = await response.json();
        const text = data.candidates?.[0]?.content?.parts?.[0]?.text || '';

        const jsonMatch = text.match(/\{[\s\S]*?\}/);
        if (jsonMatch) {
            const parsed = JSON.parse(jsonMatch[0]);
            if (parsed.player && parsed.npc) {
                return {
                    messages: [
                        { speaker: 'player', text: parsed.player },
                        { speaker: 'npc', text: parsed.npc, speakerName: opponent.name },
                    ],
                };
            }
        }

        const mock = getPersonalizedMockChat(personality);
        return {
            messages: [
                { speaker: 'player', text: mock.player },
                { speaker: 'npc', text: mock.npc },
            ],
        };
    } catch (err) {
        console.warn('Gemini API呼び出し失敗:', err);
        const mock = getPersonalizedMockChat(personality);
        return {
            messages: [
                { speaker: 'player', text: mock.player },
                { speaker: 'npc', text: mock.npc },
            ],
        };
    }
}

/** 性格パラメータから簡潔なサマリーを作る */
export function buildPersonalitySummary(personality) {
    const labels = {
        creative: window.i18next ? window.i18next.t('ui.cat_creative', { defaultValue: 'クリエイティブ' }) : 'クリエイティブ',
        physical: window.i18next ? window.i18next.t('ui.cat_physical', { defaultValue: '体を動かすのが好き' }) : '体を動かすのが好き',
        social: window.i18next ? window.i18next.t('ui.cat_social', { defaultValue: '人懐っこい' }) : '人懐っこい',
        intellectual: window.i18next ? window.i18next.t('ui.cat_intellectual', { defaultValue: '知識欲が強い' }) : '知識欲が強い',
        chaotic: window.i18next ? window.i18next.t('ui.cat_chaotic', { defaultValue: '自由奔放' }) : '自由奔放',
    };

    const sorted = Object.entries(personality)
        .sort(([, a], [, b]) => b - a)
        .filter(([, v]) => v > 0);

    if (sorted.length === 0) {
        return window.i18next ? window.i18next.t('ui.personality_newborn', { defaultValue: '生まれたばかりで性格未定' }) : '生まれたばかりで性格未定';
    }

    const connector = window.i18next && window.i18next.language === 'en' ? ' & ' : 'で';
    return sorted.slice(0, 2).map(([k]) => labels[k]).join(connector);
}

